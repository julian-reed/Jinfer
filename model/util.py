def benchmark_memory(label: str, device: str):
    process = psutil.Process(os.getpid())
    rss = process.memory_info().rss

    device_allocated = 0
    device_reserved = 0
    device_peak = -1

    if device == "cuda":
        torch.cuda.synchronize()
        device_allocated = torch.cuda.memory_allocated()
        device_reserved = torch.cuda.memory_reserved()
        device_peak = torch.cuda.max_memory_allocated()

    elif device == "mps":
        torch.mps.synchronize()
        device_allocated = torch.mps.current_allocated_memory()
        device_reserved = torch.mps.driver_allocated_memory()
  
    def mib(value):
        return value / 1024**2
  
    print(
        f"[{label}]: "
        f"RSS={mib(rss):.1f} MiB, "
        f"device allocated={mib(device_allocated):.1f} MiB, "
        f"device reserved={mib(device_reserved):.1f} MiB, "
        f"device peak={mib(device_peak):.1f} MiB"
    )
