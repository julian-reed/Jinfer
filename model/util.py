def resolve_torch_dtype(dtype):
    if isinstance(dtype, torch.dtype):
        return dtype

    if isinstance(dtype, str):
        dtype_name = dtype.removeprefix("torch.")
        resolved_dtype = getattr(torch, dtype_name, None)
        if isinstance(resolved_dtype, torch.dtype):
            return resolved_dtype

    raise TypeError(f"Unsupported torch dtype: {dtype!r}")


